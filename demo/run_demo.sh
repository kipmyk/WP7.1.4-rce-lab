set -euo pipefail

# Dynamic path resolution relative to script location
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LAB_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$LAB_DIR"

# Docker host auto-detection for local macOS Colima socket
if [ -z "${DOCKER_HOST:-}" ] && [ -S "${HOME}/.colima/default/docker.sock" ]; then
    export DOCKER_HOST="unix://${HOME}/.colima/default/docker.sock"
fi

BOLD="\033[1m"
RED="\033[31m"
GREEN="\033[32m"
YELLOW="\033[33m"
BLUE="\033[34m"
CYAN="\033[36m"
MAGENTA="\033[35m"
RESET="\033[0m"

# Track temporary directories and probe paths for safe lifecycle cleanup
TEMP_MOCK_BASE=""
PROBE_STATIC=""
PROBE_PHP=""

# Safe cleanup ensuring only script-owned temporary files are removed
cleanup() {
    if [[ -n "${PROBE_STATIC:-}" && -f "${PROBE_STATIC:-}" ]]; then
        rm -f "$PROBE_STATIC" 2>/dev/null || true
    fi
    if [[ -n "${PROBE_PHP:-}" && -f "${PROBE_PHP:-}" ]]; then
        rm -f "$PROBE_PHP" 2>/dev/null || true
    fi
    if [[ -n "${TEMP_MOCK_BASE:-}" && -d "${TEMP_MOCK_BASE:-}" && "${TEMP_MOCK_BASE}" == "${TMPDIR:-/tmp}/wp_demo_"* ]]; then
        rm -rf "${TEMP_MOCK_BASE}" 2>/dev/null || true
    fi
}

on_exit() {
    cleanup
}

on_int() {
    echo -e "\n${YELLOW}[!] Interrupted by user (SIGINT). Cleaning up temporary assets...${RESET}"
    cleanup
    trap - INT
    kill -INT "$$"
}

on_term() {
    echo -e "\n${YELLOW}[!] Terminated by signal (SIGTERM). Cleaning up temporary assets...${RESET}"
    cleanup
    trap - TERM
    kill -TERM "$$"
}

trap on_exit EXIT
trap on_int INT
trap on_term TERM

header() {
    echo -e "\n${BOLD}${BLUE}==============================================================================${RESET}"
    echo -e "${BOLD}${CYAN}$1${RESET}"
    echo -e "${BOLD}${BLUE}==============================================================================${RESET}\n"
}

badge() {
    local type="$1"
    case "$type" in
        "LIVE")            echo -e "${GREEN}[LIVE]${RESET}" ;;
        "SIMULATED")       echo -e "${YELLOW}[SIMULATED]${RESET}" ;;
        "SOURCE-VERIFIED") echo -e "${CYAN}[SOURCE-VERIFIED]${RESET}" ;;
        "HISTORICAL")      echo -e "${BLUE}[HISTORICAL]${RESET}" ;;
        "STATIC ANALYSIS") echo -e "${MAGENTA}[STATIC ANALYSIS]${RESET}" ;;
        "ILLUSTRATIVE")    echo -e "${YELLOW}[ILLUSTRATIVE]${RESET}" ;;
        *)                 echo -e "[${type}]" ;;
    esac
}

substep() {
    echo -e "\n${BOLD}>>> $1${RESET}"
}

# Helper to model relative-path file promotion matching WordPress copy_dir() logic
simulate_copy_dir() {
    local src="$1"
    local dst="$2"
    shift 2
    local skip=("$@")

    find "$src" -type f | sort | while read -r src_file; do
        rel_path="${src_file#$src/}"
        is_skipped=0
        matched_rule=""
        for skip_entry in "${skip[@]}"; do
            if [[ "$rel_path" == "$skip_entry" || "$rel_path" == "$skip_entry"/* ]]; then
                is_skipped=1
                matched_rule="$skip_entry"
                break
            fi
        done

        if [ "$is_skipped" -eq 1 ]; then
            echo "  [Filter] Skipping excluded path: $rel_path (matched: '$matched_rule')"
        else
            dst_file="$dst/$rel_path"
            mkdir -p "$(dirname "$dst_file")"
            cp -f "$src_file" "$dst_file"
            echo "  [Sync] Promoted file: $rel_path"
        fi
    done
}

run_demo_a() {
    header "DEMONSTRATION A: WordPress 7.1.3 (Vulnerable Core Baseline)"

    substep "$(badge SOURCE-VERIFIED) 1. Staging Directory Naming Derivation (wp-admin/includes/class-wp-upgrader.php)"
    echo "In WordPress 7.1.3, the working directory path is derived deterministically"
    echo "from the package filename:"
    echo '  $working_dir = $upgrade_folder . basename( basename( $package, ".tmp" ), ".zip" );'
    echo "For the tested official release package 'wordpress.zip', the staging path resolves to:"
    echo -e "  ${RED}wp-content/upgrade/wordpress/${RESET}"
    echo "Finding: Predictable for the tested 'wordpress.zip' package name."
    echo "(Note: Path depends on the package archive filename rather than a hardcoded string)."

    substep "$(badge SIMULATED) 2. Pre-Unpack Guard File Stripping"
    echo "Simulating the 7.1.3 pre-unpack cleanup routine in a unique temporary directory"
    echo "to demonstrate the underlying loop logic (unconditionally deleting all directory contents)."
    echo "Note: This is a filesystem simulation, not an active WordPress upgrade execution."
    
    TEMP_MOCK_BASE="$(mktemp -d "${TMPDIR:-/tmp}/wp_demo_XXXXXX")"
    MOCK_DIR="$TEMP_MOCK_BASE/mock_713"
    mkdir -p "$MOCK_DIR"
    echo "<?php // Silence is golden." > "$MOCK_DIR/index.php"
    echo "DUMMY_OLD_PAYLOAD" > "$MOCK_DIR/old_file.zip"
    
    echo "  Initial state: mock upgrade directory contains index.php and old_file.zip."
    # 7.1.3 cleanup logic: deletes everything unconditionally
    rm -rf "${MOCK_DIR:?}"/*
    
    if [ ! -f "$MOCK_DIR/index.php" ]; then
        echo -e "  State after 7.1.3 cleanup: ${RED}index.php DELETED${RESET} (Guard file stripped)."
        echo "  Impact: Leaves directory vulnerable to web-server autoindex directory listings if not hardened."
    fi

    substep "$(badge SIMULATED) 3. File Promotion Boundary with Relative Path Modeling"
    echo "Simulating copy_dir() using relative path traversal to evaluate the 7.1.3 exclusion list:"
    echo '  $skip = array( "wp-content", "wp-includes/version.php" );'
    echo "Note: Models nested exclusions ('wp-includes/version.php', 'wp-content/')."
    echo "Notice wp-config.php is absent from \$skip in 7.1.3."
    
    SRC_DIR="$TEMP_MOCK_BASE/src_713"
    DST_DIR="$TEMP_MOCK_BASE/dst_713"
    mkdir -p "$SRC_DIR/wp-includes" "$SRC_DIR/wp-content/plugins" "$DST_DIR/wp-includes"
    
    echo "<?php // SYNTHETIC_STAGED_CONFIG" > "$SRC_DIR/wp-config.php"
    echo "<?php // PRODUCTION_CONFIG" > "$DST_DIR/wp-config.php"
    echo "<?php // Core loader" > "$SRC_DIR/wp-load.php"
    echo "<?php \$wp_version = '7.1.3';" > "$SRC_DIR/wp-includes/version.php"
    echo "<?php // Functions" > "$SRC_DIR/wp-includes/functions.php"
    echo "<?php // Sample plugin" > "$SRC_DIR/wp-content/plugins/sample.php"

    # Execute simulation with 7.1.3 skip array
    simulate_copy_dir "$SRC_DIR" "$DST_DIR" "wp-content" "wp-includes/version.php"

    if grep -q "SYNTHETIC_STAGED_CONFIG" "$DST_DIR/wp-config.php"; then
        echo -e "  Result: ${RED}wp-config.php OVERWRITTEN${RESET} (7.1.3 promoted staged config)."
        echo "  Root Cause: Absence of 'wp-config.php' in copy_dir() exclusion array."
    fi
    if [ ! -f "$DST_DIR/wp-includes/version.php" ]; then
        echo -e "  Nested Check: ${GREEN}wp-includes/version.php correctly skipped${RESET} via relative path matching."
    fi

    substep "$(badge SOURCE-VERIFIED) 4. Research Context & Advisory Metadata"
    echo "Advisory Metadata & Assessment Distinction:"
    echo "  The WordPress GitHub Security Advisory GHSA-4w3m-c66w-69mg"
    echo "  classifies this issue as Low severity and does not publish a CVSS score."
    echo ""
    echo "  Wordfence subsequently assigned CVE-2026-119977 with a"
    echo "  CVSS 3.1 score of 8.1 (High), identifying CWE-367."
    echo ""
    echo "  These ratings are source-specific and should be reported separately."
    echo "  The behaviours demonstrated here do not independently establish"
    echo "  successful remote code execution."
}

run_demo_b() {
    header "DEMONSTRATION B: WordPress 7.1.4 (Patched Core Protections)"

    substep "$(badge SOURCE-VERIFIED) 1. Randomized Staging Directory Naming (wp-admin/includes/class-wp-upgrader.php)"
    echo "WordPress 7.1.4 replaced deterministic directory derivation with get_working_dir_name():"
    echo '  return $name . "-" . wp_generate_password( 16, false );'
    echo "Example generated directory paths for 'wordpress.zip':"
    for _ in {1..3}; do
        RAND_TOKEN=$(LC_ALL=C tr -dc 'a-zA-Z0-9' < /dev/urandom | head -c 16 || true)
        echo -e "  $(badge ILLUSTRATIVE) ${GREEN}wp-content/upgrade/wordpress-${RAND_TOKEN}/${RESET}"
    done
    echo "Note: The above samples are illustrative. In production, WordPress calls wp_generate_password(16, false)."
    echo "Security Impact: 16-character alphanumeric random suffix drastically reduces path predictability."

    substep "$(badge SIMULATED) 2. Guard File Preservation & Auto-Generation"
    echo "Simulating the two 7.1.4 guard-file handling cases in unique temporary directories:"
    echo '  Source logic: if ( "index.php" === $file["name"] ) continue;'
    echo '  and: if ( ! file_exists( $upgrade_folder . "index.php" ) ) { create empty index.php }'
    
    TEMP_MOCK_BASE="$(mktemp -d "${TMPDIR:-/tmp}/wp_demo_XXXXXX")"

    echo "  -- Case 2A: Existing index.php present before unpack --"
    MOCK_DIR_A="$TEMP_MOCK_BASE/mock_714_case1"
    mkdir -p "$MOCK_DIR_A"
    echo "<?php // Existing guard index" > "$MOCK_DIR_A/index.php"
    echo "DUMMY_OLD_ARCHIVE" > "$MOCK_DIR_A/old_file.zip"
    
    # 7.1.4 cleanup: delete files except index.php
    find "$MOCK_DIR_A" -type f ! -name "index.php" -delete
    if [ -f "$MOCK_DIR_A/index.php" ]; then
        echo -e "  Case 2A State: ${GREEN}index.php PRESERVED${RESET} (Guard file preserved during cleanup)."
    fi

    echo "  -- Case 2B: index.php absent before unpack --"
    MOCK_DIR_B="$TEMP_MOCK_BASE/mock_714_case2"
    mkdir -p "$MOCK_DIR_B"
    echo "DUMMY_OLD_ARCHIVE" > "$MOCK_DIR_B/old_file.zip"
    
    # 7.1.4 cleanup: delete old files, check if index.php exists; if not, create it
    find "$MOCK_DIR_B" -type f ! -name "index.php" -delete
    if [ ! -f "$MOCK_DIR_B/index.php" ]; then
        printf "<?php\n// Silence is golden.\n" > "$MOCK_DIR_B/index.php"
    fi
    if [ -f "$MOCK_DIR_B/index.php" ]; then
        echo -e "  Case 2B State: ${GREEN}index.php CREATED${RESET} (WordPress auto-generated missing guard file)."
    fi

    substep "$(badge SIMULATED) 3. File Promotion Exclusion with Relative Path Modeling"
    echo "Simulating copy_dir() using relative path traversal to evaluate the 7.1.4 exclusion list:"
    echo '  $skip = array( "wp-content", "wp-includes/version.php", "wp-config.php" );'
    
    SRC_DIR="$TEMP_MOCK_BASE/src_714"
    DST_DIR="$TEMP_MOCK_BASE/dst_714"
    mkdir -p "$SRC_DIR/wp-includes" "$SRC_DIR/wp-content/plugins" "$DST_DIR/wp-includes"
    
    echo "<?php // SYNTHETIC_STAGED_CONFIG" > "$SRC_DIR/wp-config.php"
    echo "<?php // PRODUCTION_CONFIG" > "$DST_DIR/wp-config.php"
    echo "<?php // Core loader" > "$SRC_DIR/wp-load.php"
    echo "<?php \$wp_version = '7.1.4';" > "$SRC_DIR/wp-includes/version.php"
    echo "<?php // Functions" > "$SRC_DIR/wp-includes/functions.php"
    echo "<?php // Sample plugin" > "$SRC_DIR/wp-content/plugins/sample.php"

    # Execute simulation with 7.1.4 skip array
    simulate_copy_dir "$SRC_DIR" "$DST_DIR" "wp-content" "wp-includes/version.php" "wp-config.php"

    if grep -q "PRODUCTION_CONFIG" "$DST_DIR/wp-config.php"; then
        echo -e "  Result: ${GREEN}wp-config.php PROTECTED${RESET} (Production config untouched; staged config skipped)."
        echo "  Verification: Legitimate production database configuration preserved across core update."
    fi
}

