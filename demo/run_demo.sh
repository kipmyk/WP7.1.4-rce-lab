run_demo_d() {
    header "DEMONSTRATION D: Server-Level Hardening Assessment"

    substep "$(badge LIVE) 1. Active Apache Configuration Verification"
    echo "Verifying active Apache configuration tree via container runtime..."
    APACHE_INCLUDES=$(docker exec wp_vuln_app apache2ctl -t -D DUMP_INCLUDES 2>&1 || true)
    if echo "$APACHE_INCLUDES" | grep -F "upgrade-hardening.conf" >/dev/null; then
        echo -e "  ${GREEN}✔ Verified:${RESET} /etc/apache2/conf-enabled/upgrade-hardening.conf is actively loaded."
    else
        echo -e "  ${RED}✖ Error:${RESET} upgrade-hardening.conf is not loaded in Apache configuration tree!"
        exit 1
    fi

    substep "$(badge LIVE) 2. Live Assertion Test on Hardened Apache (127.0.0.1:8081)"
    echo "Deploying temporary probe files into vulnerable container filesystem to test live HTTP perimeter..."
    
    mkdir -p "$LAB_DIR/vulnerable/html/wp-content/upgrade"
    PROBE_STATIC="$LAB_DIR/vulnerable/html/wp-content/upgrade/probe.txt"
    PROBE_PHP="$LAB_DIR/vulnerable/html/wp-content/upgrade/probe.php"
    echo "DEMO_STATIC_PROBE" > "$PROBE_STATIC"
    echo "<?php echo 'DEMO_PHP_PROBE'; ?>" > "$PROBE_PHP"

    STATUS_DIR=$(curl -s -o /dev/null -w "%{http_code}" "http://127.0.0.1:8081/wp-content/upgrade/")
    STATUS_TXT=$(curl -s -o /dev/null -w "%{http_code}" "http://127.0.0.1:8081/wp-content/upgrade/probe.txt")
    STATUS_PHP=$(curl -s -o /dev/null -w "%{http_code}" "http://127.0.0.1:8081/wp-content/upgrade/probe.php")
    STATUS_SITE=$(curl -s -o /dev/null -w "%{http_code}" "http://127.0.0.1:8081/")

    echo -e "  Directory Request (/wp-content/upgrade/):       HTTP ${STATUS_DIR}"
    echo -e "  Static Probe Request (/probe.txt):             HTTP ${STATUS_TXT}"
    echo -e "  PHP Probe Request (/probe.php):                HTTP ${STATUS_PHP}"
    echo -e "  Normal Site Request (/):                       HTTP ${STATUS_SITE}"

    # Genuine assertion checks - exit non-zero if any assertion fails
    ASSERTION_FAILED=0
    if [ "$STATUS_DIR" -ne 403 ]; then
        echo -e "  ${RED}ASSERTION FAILED:${RESET} Expected HTTP 403 for directory, got $STATUS_DIR"
        ASSERTION_FAILED=1
    fi
    if [ "$STATUS_TXT" -ne 403 ]; then
        echo -e "  ${RED}ASSERTION FAILED:${RESET} Expected HTTP 403 for static probe, got $STATUS_TXT"
        ASSERTION_FAILED=1
    fi
    if [ "$STATUS_PHP" -ne 403 ]; then
        echo -e "  ${RED}ASSERTION FAILED:${RESET} Expected HTTP 403 for PHP probe, got $STATUS_PHP"
        ASSERTION_FAILED=1
    fi
    if [ "$STATUS_SITE" -ne 200 ]; then
        echo -e "  ${RED}ASSERTION FAILED:${RESET} Expected HTTP 200 for site root, got $STATUS_SITE"
        ASSERTION_FAILED=1
    fi

    # Clean up probes immediately
    rm -f "$PROBE_STATIC" "$PROBE_PHP"
    PROBE_STATIC=""
    PROBE_PHP=""

    if [ "$ASSERTION_FAILED" -ne 0 ]; then
        echo -e "\n${RED}Live Apache hardening assertions failed!${RESET}"
        exit 1
    fi
    echo -e "  ${GREEN}✔ All live Apache hardening assertions passed: HTTP 403 enforced, site root 200 OK.${RESET}"

    substep "$(badge SOURCE-VERIFIED) 3. Test Scope & Defense-in-Depth Boundary"
    echo "Scope & Defense-in-Depth Context:"
    echo "  These live tests prove that the tested HTTP paths (/wp-content/upgrade/, /probe.txt, /probe.php)"
    echo "  are blocked under this specific web-server configuration. They provide perimeter defense-in-depth"
    echo "  by denying direct HTTP access to the staging directory. They do not prove that the underlying"
    echo "  application-level weakness is universally mitigated across all web servers or hosting architectures."

    substep "$(badge HISTORICAL) 4. Nginx 1.31+ Hardening Directive"
    echo "Nginx configuration verified in Phase 6 (tested in disposable container):"
    echo '  location ^~ /wp-content/upgrade/ {'
    echo '      deny all;'
    echo '      autoindex off;'
    echo '      return 403;'
    echo '  }'
    echo "  Status: Historical verification confirmed HTTP 403 for directory, static, and PHP probes."

    substep "$(badge 'STATIC ANALYSIS') 5. OpenLiteSpeed Security Directive Review"
    echo "OpenLiteSpeed configuration analyzed via syntax and directive review:"
    echo '  context /wp-content/upgrade/ {'
    echo '      type NULL'
    echo '      accessible no'
    echo '  }'
    echo "  Status: Configuration static analysis only. Not runtime validated in container environment."

    substep "$(badge HISTORICAL) 6. Core Update Compatibility Verification"
    echo "Status: Legitimate WP-CLI core updates were verified in Phase 6 to complete successfully while"
    echo "the server restriction was active, as WordPress relies strictly on local filesystem I/O (WP_Filesystem)."
}

